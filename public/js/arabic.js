  function applyLanguage(lang) {
    // Set direction and language on HTML tag
    document.documentElement.lang = lang;
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }

    // Update static texts that have data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (el.innerHTML.includes('<') && !el.innerHTML.includes('svg')) {
          // If it contains HTML (like the empty sub message), we inject as HTML
          el.innerHTML = translate(key);
      } else {
          // Check if there's an SVG we need to keep
          const svg = el.querySelector('svg');
          if (svg) {
              const textNode = Array.from(el.childNodes).find(n => n.nodeType === 3 && n.textContent.trim().length > 0);
              if (textNode) {
                  textNode.textContent = ' ' + translate(key) + ' ';
              } else {
                  el.appendChild(document.createTextNode(' ' + translate(key)));
              }
          } else {
              el.textContent = translate(key);
          }
      }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = translate(key);
    });

    // Update titles
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.title = translate(key);
    });
  }

